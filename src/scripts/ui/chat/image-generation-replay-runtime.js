import { getGeneratedImageReferenceItems } from '../image-generation-reference-utils.js';
import { restoreImagePromptFromAsset } from '../image-prompt/image-prompt-utils.js';
import { normalizeImageProviderKey } from '../image-generation-params-utils.js';
import { resolveInlineGeneratedImageAsset } from './context-menu-ui-utils.js';

// A replay owns a request snapshot, not a preset id or the mutable source job.
export const snapshotImageGenerationReplay = (generated = {}) => {
  const snapshot = JSON.parse(JSON.stringify(generated));
  const params = snapshot.generationParams && typeof snapshot.generationParams === 'object'
    ? snapshot.generationParams : {};
  params.imagePromptDocument = restoreImagePromptFromAsset({ ...snapshot, generationParams: params });
  // References are hydrated separately; never send attachment paths to a provider.
  delete params.referenceImages;
  delete params.reference_images;
  return {
    prompt: String(snapshot.prompt || '').trim(),
    provider: String(snapshot.provider || '').trim(),
    model: String(snapshot.model || '').trim(),
    generationParams: params,
  };
};

export const resolveImageGenerationReplayConfig = (config, snapshot) => {
  if (!snapshot) return config;
  if (snapshot.provider && normalizeImageProviderKey(config.provider) !== normalizeImageProviderKey(snapshot.provider)) {
    throw new Error(`当前图片渠道与原图不同，请切回 ${snapshot.provider} 后再生成`);
  }
  return snapshot.model ? { ...config, model: snapshot.model } : config;
};

export const createImageGenerationReplayRuntime = ({
  getMessage, getContextKey, loadReferences, runImageGeneration, notifyError,
} = {}) => async ({ sessionId = '', messageId = '', inlineGeneratedImage = null } = {}) => {
  const contextKey = getContextKey(sessionId);
  const message = getMessage(messageId, sessionId);
  const generated = inlineGeneratedImage
    ? resolveInlineGeneratedImageAsset(message, inlineGeneratedImage)
    : message?.meta?.generatedMedia;
  if (!message || !generated || (generated.kind && generated.kind !== 'image') || !String(generated.prompt || '').trim()) {
    notifyError?.('没有找到原始生图提示词，无法重新生成');
    return false;
  }
  try {
    // Capture before the first await: the source may finish or be retried while
    // its references are being read. Its task and message are never modified here.
    const references = getGeneratedImageReferenceItems(generated).map(item => ({ ...item }));
    const replaySnapshot = snapshotImageGenerationReplay(generated);
    const sourceMessage = { id: message.id, role: message.role, name: message.name, avatar: message.avatar };
    const surface = String(generated.surface || generated.scope?.surface || '').trim();
    const referenceImages = await loadReferences(references, sessionId);
    if (contextKey !== getContextKey(sessionId) || !getMessage(messageId, sessionId)) {
      notifyError?.('目标聊天或存档已变化');
      return false;
    }
    return await runImageGeneration({
      prompt: replaySnapshot.prompt, replaySnapshot, referenceImages,
      sourceMessage, surface, targetSessionId: sessionId,
      sourceMessageIdOverride: messageId,
      autoGenerated: false, reuseAutoImageSource: false,
    });
  } catch (error) {
    notifyError?.(error?.message || String(error));
    return false;
  }
};
