import { build } from 'esbuild';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'src/vendor/realtime/aws-signing.js');
const result = await build({
  absWorkingDir: root,
  stdin: { contents: "export { SignatureV4 } from '@smithy/signature-v4'; export { Sha256 } from '@aws-crypto/sha256-js';", resolveDir: root, sourcefile: 'realtime-aws-signing-entry.js' },
  bundle: true, platform: 'browser', format: 'esm', target: 'es2020', minify: true, metafile: true,
  legalComments: 'inline', outfile: output,
  banner: { js: '// Generated by npm run build:realtime-deps. Third-party licenses: THIRD_PARTY_LICENSES.txt' },
});
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  let dir = path.dirname(path.resolve(root, input));
  while (dir !== path.dirname(dir) && !existsSync(path.join(dir, 'package.json'))) dir = path.dirname(dir);
  if (existsSync(path.join(dir, 'package.json'))) packages.add(dir);
}
const notices = [...packages].sort().map(dir => {
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const files = readdirSync(dir).filter(name => /^(license|notice|copyright)/i.test(name));
  if (!files.length) throw new Error(`Missing license for ${pkg.name}`);
  return `${pkg.name} ${pkg.version}\n${files.map(name => readFileSync(path.join(dir, name), 'utf8')).join('\n')}`;
});
writeFileSync(path.join(path.dirname(output), 'THIRD_PARTY_LICENSES.txt'), notices.join('\n\n--------------------\n\n'));
console.log(`Realtime AWS signing bundle: ${readFileSync(output).byteLength} bytes`);
