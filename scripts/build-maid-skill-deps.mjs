import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'src/vendor/skills/yaml.js');
await build({
  absWorkingDir: root,
  stdin: { contents: "export { parseDocument, stringify, visit, isAlias } from 'yaml';", resolveDir: root, sourcefile: 'maid-skill-yaml-entry.js' },
  bundle: true, platform: 'browser', format: 'esm', target: 'es2020', minify: true, legalComments: 'inline', outfile: output,
  banner: { js: '// Generated by npm run build:maid-skill-deps. License: THIRD_PARTY_LICENSES.txt' },
});
const pkg = JSON.parse(readFileSync(path.join(root, 'node_modules/yaml/package.json'), 'utf8'));
writeFileSync(path.join(path.dirname(output), 'THIRD_PARTY_LICENSES.txt'), `yaml ${pkg.version}\n${readFileSync(path.join(root, 'node_modules/yaml/LICENSE'), 'utf8')}`);
console.log(`Skill YAML bundle: ${readFileSync(output).byteLength} bytes`);
