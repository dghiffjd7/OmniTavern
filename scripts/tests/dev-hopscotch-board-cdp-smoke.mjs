// Windows PowerShell；仅使用隔离的内存 store / 假模型，不写真实会话或请求付费模型。
import assert from 'node:assert/strict';
import { evaluateInApp } from '../dev/cdp-client.mjs';

const result = await evaluateInApp(`(async () => {
  if (!window.appBridge?.debugUiRegistry?.stores?.hopscotchTurnRuntime) throw new Error('app integration not initialized');
  window.__hopscotchSmokePanel?.dispose();
  const { createHopscotchBoardPanel } = await import('/scripts/ui/chat/hopscotch-board-panel.js');
  const { createHopscotchBoardStore } = await import('/scripts/storage/hopscotch-board-store.js');
  const { createHopscotchTurnRuntime, createHopscotchExecutors } = await import('/scripts/ui/chat/hopscotch-turn-runtime.js');
  const sessions = new Map();
  const local = new Map();
  const store = createHopscotchBoardStore({ storage: { getItem: k => local.get(k), setItem: (k, v) => local.set(k, v) }, getSessionSettings: sid => sessions.get(sid), setSessionSettings: (sid, value) => { sessions.set(sid, value); return true; } });
  let enabled = true;
  const requests = [];
  const runtime = createHopscotchTurnRuntime({ getSettings: () => ({ creativeHopscotchEnabled: enabled }), boardStore: store,
    createExecutors: info => createHopscotchExecutors({ ...info, custom: { backgroundChat: async messages => { requests.push(messages); return requests.length === 1 ? '分析资料' : '只读建议'; }, getRecentMessages: () => [], getBodyText: () => '正文示例' } }) });
  const panel = createHopscotchBoardPanel({ boardStore: store, runtime, getSessionId: () => 'rp:hopscotch-smoke', enable: value => { enabled = value; }, getEnabled: () => enabled });
  panel.show();
  const root = document.querySelector('dialog.hop-dialog[open]');
  if (!root) throw new Error('editor did not open');
  const click = (selector, parent = root) => { const node = parent.querySelector(selector); if (!node) throw new Error('missing ' + selector); node.click(); };
  click('[data-hop-add="0"][data-hop-new="1"]');
  click('[data-action="add:custom_prompt"]', document.querySelector('dialog.hop-detail[open]'));
  const pre = root.querySelector('[data-hop-house]').dataset.hopHouse;
  click('[data-hop-house="' + pre + '"]');
  let dialog = document.querySelector('dialog.hop-detail[open]');
  click('[data-action="flip"]', dialog);
  dialog.querySelector('[name="label"]').value = '分析';
  dialog.querySelector('[name="prompt"]').value = '分析 {{user_input}}';
  dialog.querySelector('[name="includeContext"]').value = 'none';
  dialog.querySelector('[name="injectIntoBody"]').checked = true;
  click('[data-action="apply"]', dialog);
  const rowCount = root.querySelectorAll('[data-hop-row]').length;
  click('[data-hop-add="' + rowCount + '"][data-hop-new="1"]');
  click('[data-action="add:custom_prompt"]', document.querySelector('dialog.hop-detail[open]'));
  const houses = [...root.querySelectorAll('[data-hop-house]')];
  const post = houses.at(-1).dataset.hopHouse;
  click('[data-hop-house="' + post + '"]');
  dialog = document.querySelector('dialog.hop-detail[open]');
  click('[data-action="flip"]', dialog);
  dialog.querySelector('[name="label"]').value = '编修建议';
  dialog.querySelector('[name="prompt"]').value = '建议 {{body}}';
  dialog.querySelector('[name="includeContext"]').value = 'none';
  dialog.querySelector('[name="outputMode"]').value = 'note';
  click('[data-action="apply"]', dialog);
  click('[data-action="save"]');
  await new Promise(resolve => setTimeout(resolve, 50));
  const saved = store.getSessionOverride('rp:hopscotch-smoke');
  if (!saved) throw new Error(root.querySelector('.hop-error').textContent || 'save failed');
  const turn = runtime.prepareTurn({ sessionId: 'rp:hopscotch-smoke', rpUiMode: true, text: '雨夜' });
  const start = await turn.waitForBodyStart();
  const injection = turn.getPromptBlocks();
  turn.resolveBody({ status: 'succeeded', messageId: 'smoke-body' });
  const outcome = await turn.turnPromise;
  click('[data-action="run-mode"]');
  click('[data-hop-house="' + post + '"]');
  dialog = document.querySelector('dialog.hop-detail[open]');
  if (!dialog.querySelector('.hop-card-front').textContent.includes('只读建议')) throw new Error('runtime card lost note output');
  click('[data-action="flip"]', dialog);
  if (!dialog.querySelector('fieldset').disabled || dialog.querySelector('[data-action="apply"]')) throw new Error('runtime snapshot is editable');
  click('[data-action="close-detail"]', dialog);
  const rows = [...root.querySelectorAll('[data-hop-row]')].map(el => el.getBoundingClientRect().y);
  const answer = { start: start.proceed, savedRows: saved.rows.length, injection: injection.map(b => b.content), requests: requests.length, status: outcome.status, topDown: rows.every((y, i) => i === 0 || y > rows[i - 1]), note: outcome.artifacts[post].text, appEntry: window.appBridge.debugUiRegistry.panels.agentCenterPanel.getHopscotchPanel() === window.appBridge.debugUiRegistry.stores.hopscotchBoardPanel && !document.getElementById('hopscotch-board-trigger') };
  window.__hopscotchSmokePanel = panel;
  return answer;
})()`);
assert.equal(result.start, true);
assert.equal(result.requests, 2);
assert.equal(result.status, 'succeeded');
assert.equal(result.topDown, true);
assert.equal(result.appEntry, true);
assert.ok(result.injection[0].includes('分析资料'));
assert.equal(result.note, '只读建议');
console.log('ok - dev board edit/save → pre → body → readonly note, top-down runtime view', result);
