assert.equal(cache.get({...field}),diff,'repeated rendering/scrolling reuses the diff');
assert.equal(applyAgentPromptDiffHunk(diff,0,'accept'),'FIRST\nkeep\nlast');
assert.equal(applyAgentPromptDiffHunk(diff,1,'reject'),'FIRST\nkeep\nlast');
assert.equal(applyAgentPromptDiffHunk(diff,2,'accept'),null);
assert.equal(applyAgentPromptDiffHunk(diff,NaN,'reject'),null);
assert.equal(cache.get({...field,value:'FIRST\nkeep\nlast'}).hunks,1);
const deletion=cache.get({...field,value:''});
assert.equal(deletion.changed,true);
assert.equal(applyAgentPromptDiffHunk(deletion,0,'reject'),field.baseValue);
const html=renderAgentPromptDiff(diff,'prompt');
assert(html.includes('<del') && html.includes('<ins'));
assert.equal((html.match(/data-prompt-diff-action="accept"/g)||[]).length,2);
assert(renderAgentPromptDiff(cache.get({id:'x',baseValue:'a',value:'<img src=x onerror=evil()>'}),'x').includes('&lt;img'));
const target={fieldId:'prompt',exact:true};
assert.equal(isAgentPromptInlineEditable(target,field.value,field),true);
assert.equal(isAgentPromptInlineEditable({...target,exact:false},field.value,field),false);
assert.equal(isAgentPromptInlineEditable(target,'macro expanded',field),false);
assert.equal(isAgentPromptInlineEditable({...target,fieldId:'row:1'},field.value,field),false);
const memoryField={id:'memory:outline:plot',value:'label'};
assert.equal(isAgentPromptInlineEditable({fieldId:memoryField.id,parentKey:'memory:data',exact:true},'label',memoryField),false,'a table value that equals a label must stay read-only');
assert.equal(isAgentPromptInlineEditable({fieldId:'memory:guide:output_instruction',parentKey:'memory:guide',exact:true},'guide',{id:'memory:guide:output_instruction',value:'guide'}),true);
console.log('PASS preset-compatible hunk semantics, cache, escaping, deletion and exact ownership');

