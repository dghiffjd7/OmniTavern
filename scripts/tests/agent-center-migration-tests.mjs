import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { AgentCenterPanel } from '../../src/scripts/ui/agent-center-panel.js';
import { captureAgentEditorDrafts, restoreAgentEditorDrafts } from '../../src/scripts/ui/agent-editor-draft-utils.js';

const panel = new AgentCenterPanel({ getHopscotchPanel: () => ({}) });
const cards = panel.getAgentCards();
const html = panel.renderAgents();
assert.match(html, /hop-agent-shelf/);
assert.doesNotMatch(html, /agent-center-agent-list|agent-center-agent-card-description/);
for (const card of cards) assert.ok(html.includes(`data-agent-card-open="${card.id}"`), `${card.id} remains reachable`);
assert.match(panel.renderPromptModules(), /hop-agent-shelf/);
assert.match(panel.renderDiagnostics(), /hop-agent-shelf/);
const memory = panel.getAgentCardById('memory_table_agent');
assert.match(panel.renderAgentConfiguration(memory), /data-memory-agent-save/);
assert.match(panel.renderFloatingAgentBack(memory), /data-memory-agent-save/);
assert.match(panel.renderAgentConfiguration(memory, { preview: false }), /data-memory-agent-save/);
assert.doesNotMatch(panel.renderAgentConfiguration(memory, { preview: false }), /data-agent-prompt-preview/, '融合配置不能把独立任务预览冒充正文请求');
assert.match(panel.renderAgentConfiguration(memory), /data-agent-prompt-preview/, '原独立 Agent 仍保留预览');
const reply = panel.getAgentCardById('reply_check');
assert.match(panel.renderAgentConfiguration(panel.getAgentCardById('image_director')), /data-agent-card-action/);
assert.match(panel.renderAgentConfiguration(panel.getAgentCardById('moment_agent')), /data-agent-card-action/);
assert.match(panel.renderAgentConfiguration(reply), /data-agent-feature-model-select/);
assert.doesNotMatch(panel.renderAgentConfiguration(reply), /data-agent-float-close|data-agent-float-flip/);
const surface = panel.renderFloatingAgentCard({ agent: reply, frontExtra: '<p>本轮结果</p>', entering: true });
assert.match(surface, /agent-center-floating-card is-entering/);
assert.match(surface, /agent-center-agent-badge/);
assert.match(surface, /本轮结果/);
assert.match(surface, /data-agent-prompt-preview="reply_check"/);
assert.doesNotMatch(surface, /hop-unified-card|hop-shared-settings/);
const removable = panel.renderFloatingAgentCard({ agent: memory, toolbarExtra: '<button data-action="remove">Delete</button>' });
assert.equal((removable.match(/data-action="remove"/g) || []).length, 2, '房子删除在正反面顶部均可见');
assert.doesNotMatch(surface, /data-action="remove"/, '普通 Agent 卡片不提供全局删除');
assert.equal(typeof panel.mountHopscotchAgentCard, 'function');
const css = await readFile(new URL('../../src/assets/css/hopscotch-board.css', import.meta.url), 'utf8');
assert.doesNotMatch(css, /hop-unified-card/, '不能覆盖备份原卡片的尺寸、渐变和翻面设计');
console.log('ok - compact catalog retains every Agent, prompt and diagnostic; shared configuration uses existing editors');

const field = (value, base = 'saved') => ({ tagName: 'TEXTAREA', type: 'textarea', dataset: { agentPromptRules: '' }, name: '', value, defaultValue: base });
const root = (presetId, fields) => ({ ownerDocument: {}, querySelectorAll: () => [{ dataset: { agentPromptEditor: 'image', agentId: 'image_director', agentPromptProfileType: 'sysprompt', agentPromptPresetId: presetId }, querySelectorAll: () => fields }] });
const draft = captureAgentEditorDrafts(root('p1', [field('unsaved')]));
assert.equal(draft.editors.length, 1);
const same = field('server-update', 'server-update');
restoreAgentEditorDrafts(root('p1', [same]), draft);
assert.equal(same.value, 'unsaved');
const other = field('other-preset', 'other-preset');
restoreAgentEditorDrafts(root('p2', [other]), draft);
assert.equal(other.value, 'other-preset', '旧预设草稿不能覆盖新预设');
const committed = field('unsaved', 'unsaved');
restoreAgentEditorDrafts(root('p1', [committed]), draft);
assert.equal(captureAgentEditorDrafts(root('p1', [committed])).editors.length, 0, '成功保存后的新默认值自动成为基线');
console.log('ok - manual editor drafts survive refresh, clear on committed values and stay bound to resource identity');
