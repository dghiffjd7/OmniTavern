// Windows PowerShell + 真实 dev WebView；编辑仅用隔离内存配置，不请求模型。
import assert from 'node:assert/strict';
import { evaluateInApp } from '../dev/cdp-client.mjs';

const result = await evaluateInApp(`(async () => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const click = (root, selector) => {
    const alias = { '[data-action="flip"]': '.agent-center-floating-face:not([inert]) [data-agent-float-flip]', '[data-action="close-detail"]': '.agent-center-floating-face:not([inert]) [data-agent-float-close]' };
    const node = root.querySelector(selector) || root.querySelector(alias[selector] || selector); check(node, 'missing ' + selector); node.click();
  };
  for (let i = 0; i < 100 && !window.appBridge?.debugUiRegistry?.stores?.hopscotchBoardPanel; i++) await new Promise(resolve => setTimeout(resolve, 100));
  window.__hopscotchSmokePanel?.dispose();
  window.__agentCenterHopscotchSmoke?.dispose();
  window.__agentCenterMigrationSmoke?.dispose();
  const registry = window.appBridge.debugUiRegistry;
  const actual = registry.panels.agentCenterPanel;
  check(actual.hide() !== false, '真实 AC 有未保存草稿，停止烟测');
  registry.actions.openAgentCenter();
  await actual.refresh();
  check(actual.activeTab === 'agents', 'existing entry did not open board homepage');
  const actualRoot = actual.contentElement.querySelector('[data-agent-hopscotch-host] > .hop-embedded');
  check(actualRoot?.querySelector('[data-hop-house]'), 'real AC missing board');
  check(!actual.contentElement.querySelector('[data-agent-library]').open, 'legacy library should start folded');
  click(actualRoot, '[data-hop-house]');
  let detail = document.querySelector('.hop-house-detail[open]');
  check(detail && detail.querySelector('.agent-center-floating-face-back').inert, 'card should float with front face');
  click(detail, '[data-action="flip"]');
  check(detail.querySelector('.agent-center-floating-face-front').inert, 'front must be inert after flip');
  registry.actions.showPromptPreviewModal('isolated preview', 'AC back-order smoke', { request: { messages: [{ role: 'user', content: 'test only' }] }, initialTab: 'prompt' });
  registry.actions.closeTopAppLayer();
  check(document.getElementById('prompt-preview-overlay').style.display === 'none' && detail.open, 'app back must close prompt preview before its house card');
  click(detail, '[data-action="close-detail"]');
  actual.hide();
  actual.show({ tab: 'activity' });
  await actual.refresh();
  check(actual.activeTab === 'activity', 'activity deep link lost');
  actual.hide();

  const { AgentCenterPanel } = await import('/scripts/ui/agent-center-panel.js');
  const { createHopscotchBoardPanel } = await import('/scripts/ui/chat/hopscotch-board-panel.js');
  const { createHopscotchBoardStore } = await import('/scripts/storage/hopscotch-board-store.js');
  const { createHopscotchTurnRuntime } = await import('/scripts/ui/chat/hopscotch-turn-runtime.js');
  const sessions = new Map();
  const local = new Map();
  let enabled = false;
  let enableCalls = 0;
  let currentSid = 'rp:ac-smoke';
  let pauseSave = false;
  let finishSave;
  let executions = 0;
  const store = createHopscotchBoardStore({ storage: { getItem: k => local.get(k), setItem: (k, v) => local.set(k, v) }, getSessionSettings: id => sessions.get(id), setSessionSettings: async (id, value) => { if (pauseSave) await new Promise(resolve => { finishSave = resolve; }); sessions.set(id, value); return true; } });
  const runtime = createHopscotchTurnRuntime({ boardStore: store, getSettings: () => ({ creativeHopscotchEnabled: enabled }), createExecutors: () => { executions++; throw new Error('configuration must not execute'); } });
  let board;
  const ac = new AgentCenterPanel({ getActions: () => ({}), getHopscotchPanel: () => board });
  board = createHopscotchBoardPanel({ embedded: true, boardStore: store, runtime, getSessionId: () => currentSid, onOpen: () => ac.show(), mountAgentCard: (host, options) => ac.mountHopscotchAgentCard(host, options), getEnabled: () => enabled, enable: value => { enabled = value; enableCalls++; } });
  window.__agentCenterHopscotchSmoke = { ac, board, dispose: () => { ac.destroy(); board.dispose(); } };
  board.show();
  await ac.refresh();
  const root = ac.contentElement.querySelector('.hop-embedded');
  click(root, '[data-hop-add="0"][data-hop-new="1"]');
  click(document.querySelector('.hop-detail[open]'), '[data-action="add:custom_prompt"]');
  const houseId = root.querySelector('[data-hop-house]').dataset.hopHouse;
  await ac.refresh();
  check(root === ac.contentElement.querySelector('.hop-embedded'), 'refresh replaced editor node');
  check(root.querySelector('[data-hop-house="' + houseId + '"]'), 'refresh lost draft house');
  click(root, '[data-hop-house="' + houseId + '"]');
  detail = document.querySelector('.hop-house-detail[open]');
  click(detail, '[data-action="flip"]');
  const input = detail.querySelector('[name="label"]');
  input.value = '保留草稿';
  detail.querySelector('[name="prompt"]').value = '分析 {{user_input}}';
  click(detail, '[data-action="flip"]');
  click(detail, '[data-action="flip"]');
  await ac.refresh();
  check(detail.querySelector('[name="label"]') === input && input.value === '保留草稿', 'refresh / flip lost form input');
  click(detail, '[data-action="apply"]');
  ac.setActiveTab('activity');
  ac.setActiveTab('agents');
  check(root.textContent.includes('保留草稿'), 'tab switch lost board draft');
  ac.openFloatingAgentCard('reply_check');
  check(ac.contentElement.querySelector('.agent-center-floating-card'), 'legacy agent details lost');
  ac.toggleFloatingAgentCard();
  check(ac.contentElement.querySelector('.agent-center-floating-card.is-flipped'), 'legacy agent cannot flip');
  ac.closeTopLayer();
  check(ac.isVisible() && !ac.floatingAgentId, 'back should only close floating card');
  check(!enabled && !store.getSessionOverride('rp:ac-smoke'), 'view / edit changed effective board before save');
  check(ac.hide() === false && ac.isVisible(), 'close discarded unsaved draft');
  click(document.querySelector('.hop-detail[open]'), '[data-action="close-detail"]');
  click(root, '[data-action="save"]');
  for (let i = 0; i < 50 && (!enabled || !store.getSessionOverride('rp:ac-smoke')); i++) await new Promise(resolve => setTimeout(resolve, 20));
  check(enabled && store.getSessionOverride('rp:ac-smoke')?.rows.length === 2, 'save did not persist isolated board: ' + JSON.stringify({ enabled, rows: store.getSessionOverride('rp:ac-smoke')?.rows.length, error: root.querySelector('.hop-error').textContent }));
  check(executions === 0, 'view / flip / save invoked model executor');
  // 再加一并行格，覆盖宽行与窄行交界处的中心线。
  click(root, '[data-hop-add="0"][data-hop-new="0"]');
  click(document.querySelector('.hop-detail[open]'), '[data-action="add:custom_prompt"]');
  pauseSave = true;
  click(root, '[data-action="save"]');
  check(finishSave, 'delayed save did not start');
  board.close();
  currentSid = 'rp:next-smoke';
  ac.render();
  click(root, '[data-hop-add="0"][data-hop-new="1"]');
  click(document.querySelector('.hop-detail[open]'), '[data-action="add:custom_prompt"]');
  const nextId = root.querySelector('[data-hop-house]').dataset.hopHouse;
  finishSave();
  await new Promise(resolve => setTimeout(resolve, 50));
  check(root.querySelector('[data-hop-house="' + nextId + '"]'), 'late save erased another session draft');
  check(enableCalls === 1, 'late save changed feature switch after editor lifecycle ended');
  check(!store.getSessionOverride('rp:next-smoke'), 'late save wrote to another session');
  pauseSave = false;
  board.close();
  currentSid = 'rp:ac-smoke';
  ac.render();
  const centers = [...root.querySelectorAll('.hop-gap, .hop-row, .hop-roof')].map(node => { const r = node.getBoundingClientRect(); return r.left + r.width / 2; });
  check(Math.max(...centers) - Math.min(...centers) < 1, 'inter-row plus not centered');
  const bodyCell = root.querySelector('.hop-body');
  bodyCell.click();
  detail = document.querySelector('.hop-house-detail[open]');
  check(detail.querySelector('.hop-card-mark').textContent === bodyCell.querySelector('.hop-number').textContent, 'floating card changed house number');
  click(detail, '[data-action="close-detail"]');
  window.__agentCenterHopscotchSmoke = { ac, board, root, dispose: () => { ac.destroy(); board.dispose(); } };
  return { realEntry: true, floatingFlip: true, draftPreserved: true, savedRows: store.getSessionOverride('rp:ac-smoke').rows.length, executions, centerSpread: Math.max(...centers) - Math.min(...centers) };
})()`);
assert.equal(result.executions, 0);
assert.equal(result.savedRows, 2);
assert.ok(result.centerSpread < 1);
console.log('ok - real AC entry + isolated board mount/flip/draft/back/save/center geometry', result);
